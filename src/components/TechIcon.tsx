interface TechIconProps {
  name: string;
  className?: string;
}

export function TechIcon({ name, className = "size-3.5" }: TechIconProps) {
  const normalizedKey = name.trim().toLowerCase();
  const IconComponent = ICON_MAP[normalizedKey];

  if (!IconComponent) return null;

  // Custom multi-color icons handle their own fills
  if (normalizedKey === "playwright" || normalizedKey === "langfuse") {
    return <IconComponent className={className} />;
  }

  const brandColor = BRAND_COLORS[normalizedKey];

  return (
    <IconComponent
      className={className}
      style={brandColor ? { color: brandColor } : undefined}
    />
  );
}
